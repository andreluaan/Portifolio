"""Cuts the two borrowed fonts of the andreluaan.dev brand down to the few glyphs the site uses.

- The round dot: Geist draws "." square and the brand wants it round, so every "." comes from Zen Maru Gothic at
  the matching weight (Light -> 300, Regular -> 400, Medium -> 500, SemiBold and up -> 700).
- The kana: Geist has no Japanese. The katakana name and the seal glyphs (secrets, the passport button) come from
  Shippori Mincho B1, cut to exactly those characters.

Run after changing a seal glyph or the katakana: python scripts/fonts/subset.py
Needs: pip install fonttools brotli. Reads node_modules/@fontsource/*, writes public/fonts/ and
src/styles/brand-fonts.css (both committed, so a build never needs Python).
"""

import re
from pathlib import Path

from fontTools import subset
from fontTools.merge import Merger
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[2]
MODULES = ROOT / "node_modules" / "@fontsource"
OUTPUT = ROOT / "public" / "fonts"
CSS = ROOT / "src" / "styles" / "brand-fonts.css"

KATAKANA = "アンドレ・ルアン"
# The seal on the secrets button, plus every secret's glyph (read from the source so the two never drift)
SECRETS_SOURCE = (ROOT / "src" / "lib" / "secrets.ts").read_text(encoding="utf-8")
SEALS = "秘" + "".join(re.findall(r"glyph: '(.)'", SECRETS_SOURCE))

# font-weight range of Geist -> the Zen Maru Gothic weight that draws its dot
DOT_WEIGHTS = {300: "100 349", 400: "350 449", 500: "450 549", 700: "550 900"}


def cut(source: Path, text: str, target: Path, flavor: str | None = "woff2") -> int:
    font = TTFont(source)
    options = subset.Options()
    options.flavor = flavor
    options.layout_features = []
    options.name_IDs = []
    options.notdef_outline = False
    subsetter = subset.Subsetter(options)
    subsetter.populate(text=text)
    subsetter.subset(font)
    font.flavor = flavor
    font.save(target)
    return target.stat().st_size


def has_all(source: Path, text: str) -> str:
    cmap = TTFont(source).getBestCmap()
    return "".join(char for char in text if ord(char) in cmap)


OUTPUT.mkdir(parents=True, exist_ok=True)
faces = [
    "/* Generated by scripts/fonts/subset.py: do not edit by hand. */",
    "",
    "/* Every '.' is round (brand rule): this family covers only U+002E and sits first in every font stack. */",
]
for weight, span in DOT_WEIGHTS.items():
    name = f"ponto-{weight}.woff2"
    size = cut(MODULES / "zen-maru-gothic" / "files" / f"zen-maru-gothic-latin-{weight}-normal.woff2", ".", OUTPUT / name)
    print(f"{name}: {size} B")
    faces.append(
        f"@font-face {{\n  font-family: 'Ponto';\n  src: url('/fonts/{name}') format('woff2');\n"
        f"  font-weight: {span};\n  font-display: swap;\n  unicode-range: U+002E;\n}}"
    )

# Shippori's Japanese is split by fontsource into numbered chunks: each glyph is cut from the chunk that holds it,
# and the pieces are merged into one small file
wanted = "".join(dict.fromkeys(KATAKANA + SEALS))
remaining = wanted
pieces = []
for chunk in sorted((MODULES / "shippori-mincho-b1" / "files").glob("shippori-mincho-b1-*-500-normal.woff2")):
    found = has_all(chunk, remaining)
    if not found:
        continue
    piece = OUTPUT / f"kana-piece-{len(pieces)}.ttf"
    cut(chunk, found, piece, flavor=None)
    pieces.append(piece)
    remaining = "".join(char for char in remaining if char not in found)
    if not remaining:
        break
if remaining:
    raise SystemExit(f"no chunk has: {remaining}")
kana = Merger().merge([str(piece) for piece in pieces])
kana.flavor = "woff2"
kana.save(OUTPUT / "kana.woff2")
for piece in pieces:
    piece.unlink()
print(f"kana.woff2: {(OUTPUT / 'kana.woff2').stat().st_size} B ({wanted})")
ranges = ",".join(f"U+{ord(char):04X}" for char in wanted)
faces += [
    "",
    "/* Katakana and seal glyphs, Shippori Mincho B1 Medium, cut to the characters the site shows. */",
    f"@font-face {{\n  font-family: 'Kana';\n  src: url('/fonts/kana.woff2') format('woff2');\n"
    f"  font-weight: 500;\n  font-display: swap;\n  unicode-range: {ranges};\n}}",
]

CSS.write_text("\n".join(faces) + "\n", encoding="utf-8")
print(f"wrote {CSS.relative_to(ROOT)}")
